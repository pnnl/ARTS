#!/bin/sh
# sar_make_incbin_wrapper.sh — generate a GNU as .S wrapper that uses
# .incbin to embed a SAR .bin dataset file into an object file without
# parsing the binary data as a C source (which is what sar_dataImage does
# and which requires 10+ GB of RAM for the medium/large sizes on a
# 12 GB laptop).
#
# The .bin file layout is binary-identical to the C struct array the SAR
# source expects (verified: Data.bin size == 2 * P1 * S1 * sizeof(struct
# {int32_t real; int32_t imag;})).  We split it in half and emit two
# symbols corresponding to image_0/image_1 (or platform_0/platform_1 or
# pulse_0/pulse_1) that the app code extern-declares.
#
# Usage:
#   sar_make_incbin_wrapper.sh <bin-path> <out.S> <sym_prefix>
#
#   sym_prefix is one of: image, platform, pulse
#
# The assembled .o uses ~0 KB of compiler memory regardless of dataset
# size — .incbin copies bytes directly in the assembler.
set -eu

BIN="$1"
OUT="$2"
SYM="$3"

if [ ! -f "$BIN" ]; then
    echo "sar_make_incbin_wrapper: missing input $BIN" >&2
    exit 1
fi

TOTAL=$(stat -c %s "$BIN")
# SAR data always has numImages=2 (RAG_NumberImages=2 in Parameters.h for
# every size).  Each half is a separate symbol.
if [ $((TOTAL % 2)) -ne 0 ]; then
    echo "sar_make_incbin_wrapper: $BIN size $TOTAL is odd, expected even" >&2
    exit 1
fi
HALF=$((TOTAL / 2))

# Absolute path so .incbin finds it regardless of assembler CWD.
BIN_ABS=$(readlink -f "$BIN")

cat > "$OUT" <<EOF
/* AUTO-GENERATED by sar_make_incbin_wrapper.sh — do not edit.
 *
 * This .S file emits two symbols (${SYM}_0 and ${SYM}_1) backed by the
 * raw bytes of ${BIN_ABS}, which is binary-identical to the two halves
 * of the C struct array the SAR source expects.
 *
 * Using .incbin here instead of letting sar_dataImage emit a C source
 * file avoids loading hundreds of MB of hex-literal text through the
 * C front-end — critical for building SAR medium/large on a 12 GB box.
 */
	.section .rodata
	.align 16
	.globl ${SYM}_0
	.type ${SYM}_0, @object
	.size ${SYM}_0, ${HALF}
${SYM}_0:
	.incbin "${BIN_ABS}", 0, ${HALF}

	.align 16
	.globl ${SYM}_1
	.type ${SYM}_1, @object
	.size ${SYM}_1, ${HALF}
${SYM}_1:
	.incbin "${BIN_ABS}", ${HALF}, ${HALF}

#if defined(__linux__) && defined(__ELF__)
	.section .note.GNU-stack,"",%progbits
#endif
EOF
